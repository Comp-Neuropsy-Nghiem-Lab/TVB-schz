"""
utils/results_io.py

Loaders that turn raw .npy output (EI-tuning results, classification scores,
graph shuffles) into the plain arrays / DataFrames used by visualization.ipynb.
No plotting or statistics here — see utils/plotting.py for that.
"""

import re
from pathlib import Path

import numpy as np
import pandas as pd

CTRL_SCHZ_RE = re.compile(r"[A-Za-z]+")


def group_of(subject):
    """'ctrl0' -> 'ctrl', 'schz14' -> 'schz'."""
    match = CTRL_SCHZ_RE.match(subject)
    return match.group(0) if match else subject


def load_ei_result(results_dir, task, weight_type, parc, subject):
    """Load a single EI-tuning output file (see tasks/ei_tuning.py `save`)."""
    path = Path(results_dir) / task / weight_type / f"parc{parc}" / f"{subject}.npy"
    return np.load(path, allow_pickle=True).item()


def list_subjects(results_dir, task, weight_type, parc):
    result_dir = Path(results_dir) / task / weight_type / f"parc{parc}"
    if not result_dir.exists():
        return []
    return sorted(f.stem for f in result_dir.glob("*.npy"))


def load_J_i_by_group(results_dir, task, weight_type, parc):
    """
    Stack J_i vectors per group for one (task, weight_type, parc).
    Returns {"ctrl": array[n_ctrl, n_regions], "schz": array[n_schz, n_regions]}.
    """
    by_group = {"ctrl": [], "schz": []}
    for subject in list_subjects(results_dir, task, weight_type, parc):
        group = group_of(subject)
        if group not in by_group:
            continue
        data = load_ei_result(results_dir, task, weight_type, parc, subject)
        by_group[group].append(np.asarray(data["J_i"]).flatten())
    return {group: np.array(vectors) for group, vectors in by_group.items()}


def load_fc_fit_quality(results_dir, task, weight_type, parc):
    """
    Final FC correlation / RMSE per subject for one (task, weight_type, parc).
    Returns a DataFrame with columns: subject, group, fc_corr, fc_rmse.
    """
    rows = []
    for subject in list_subjects(results_dir, task, weight_type, parc):
        data = load_ei_result(results_dir, task, weight_type, parc, subject)
        rows.append(
            {
                "subject": subject,
                "group": group_of(subject),
                "fc_corr": float(data["fc_corr_history"][-1]),
                "fc_rmse": float(data["fc_rmse_history"][-1]),
            }
        )
    return pd.DataFrame(rows)


def load_classification_results(save_dir, classifier, exp):
    """Load one output file written by run_classification.py."""
    path = Path(save_dir) / f"{classifier}_{exp}.npy"
    return np.load(path, allow_pickle=True).item()


def classification_results_to_frame(results):
    """
    Flatten one run_classification.py result dict (see tasks/classification.py
    `ClassificationBase.run`) into a tidy, long-format DataFrame:
    columns = classifier, exp, feature, weight_metric, split, score.
    """
    classifier = results["classifier"]
    exp = results["result_exp"]
    rows = []

    for feature, by_weight_metric in results["by_metric"].items():
        for weight_metric, scored in by_weight_metric.items():
            for split, score in enumerate(scored["scores"]):
                rows.append(
                    {
                        "classifier": classifier,
                        "exp": exp,
                        "feature": feature,
                        "weight_metric": weight_metric,
                        "split": split,
                        "score": score,
                    }
                )

    for feature, scored in results["fc_only"].items():
        for split, score in enumerate(scored["scores"]):
            rows.append(
                {
                    "classifier": classifier,
                    "exp": exp,
                    "feature": feature,
                    "weight_metric": "FC",
                    "split": split,
                    "score": score,
                }
            )

    return pd.DataFrame(rows)


def load_all_classification_results(save_dir, classifiers, exps):
    """Load + concatenate every (classifier, exp) combination that exists on disk."""
    frames = []
    for classifier in classifiers:
        for exp in exps:
            path = Path(save_dir) / f"{classifier}_{exp}.npy"
            if not path.exists():
                continue
            results = load_classification_results(save_dir, classifier, exp)
            frames.append(classification_results_to_frame(results))
    if not frames:
        return pd.DataFrame(columns=["classifier", "exp", "feature", "weight_metric", "split", "score"])
    return pd.concat(frames, ignore_index=True)


def load_graph_shuffle_matrices(shuffle_dir, weight_type, sparsity):
    """Erdos-Renyi surrogate graphs generated by utils/generate_shuffles.py."""
    sparsity_int = int(round(float(sparsity) * 100))
    path = Path(shuffle_dir) / "graph_shuffles" / f"{weight_type}_er_spars{sparsity_int:03d}.npy"
    return np.load(path)


def load_graph_shuffle_fit_quality(results_dir, weight_type, parc, sparsities):
    """
    Final FC correlation for every fitted graph_idx, across sparsities, for
    task="shuffle_graph" (see tasks/ei_tuning.py ShuffleGraphEITuning).
    Returns a tidy DataFrame with columns: sparsity, graph_idx, fc_corr, fc_rmse.
    """
    rows = []
    for sparsity in sparsities:
        spar_dir = Path(results_dir) / "shuffle_graph" / weight_type / f"parc{parc}" / f"spar_{sparsity}"
        if not spar_dir.exists():
            continue
        for file_path in sorted(spar_dir.glob("shuf_*.npy")):
            data = np.load(file_path, allow_pickle=True).item()
            rows.append(
                {
                    "sparsity": sparsity,
                    "graph_idx": file_path.stem,
                    "fc_corr": float(data["fc_corr_history"][-1]),
                    "fc_rmse": float(data["fc_rmse_history"][-1]),
                }
            )
    return pd.DataFrame(rows)
